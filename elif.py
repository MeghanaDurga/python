num1 = int(input('enter num1 value:'))
num2 = int(input('enter num2 value:'))
operator = input('enter operator:')
if operator=='+':
         print(num1+num2) 
elif operator=='-':
         print(num1-num2)
elif operator=='*':
         print(num1*num2)
elif operator=='/':
          print(num1/num2)
else:
      print("not valid")         
